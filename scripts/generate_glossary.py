# Метео-термины, от которых строятся производные
_DERIVABLE = [term for term, _, cat in BASE_TERMS if cat == "метеорология"]


def build_glossary(min_terms: int = 500) -> list[dict[str, str]]:
    """База + систематические производные до min_terms (детерминированно)."""
    glossary: list[dict[str, str]] = [
        {"term": term, "definition": definition, "category": category}
        for term, definition, category in BASE_TERMS
    ]
    seen = {entry["term"] for entry in glossary}

    def add(term: str, definition: str, category: str) -> None:
        if term not in seen and len(glossary) < 2 * min_terms:
            seen.add(term)
            glossary.append({"term": term, "definition": definition, "category": category})

    # 1) Климатические нормы и аномалии для метеовеличин
    for term in _DERIVABLE:
        add(
            f"Климатическая норма: {term}",
            f"Многолетнее среднее {term} за данный календарный период; база для расчёта аномалий.",
            "климатология",
        )
    for term in _DERIVABLE:
        add(
            f"Аномалия {term}",
            f"Отклонение {term} от климатической нормы; ключевой признак экстремумов (жара/заморозки).",
            "климатология",
        )

    # 2) Лаговые признаки метеовеличин
    for lag in (1, 2, 3, 5, 7, 10, 14, 21, 30):
        for term in _DERIVABLE:
            add(
                f"Лаг {term} (k={lag} сут)",
                f"Значение {term} k дней назад; лаговые признаки для ML-моделей.",
                "признаки",
            )

    # 3) Скользящие статистики
    for window in (3, 7, 14, 30, 90):
        for term in _DERIVABLE[:12]:  # основные величины
            add(
                f"Скользящее среднее {term} (окно {window} сут)",
                f"Среднее {term} за последние {window} суток; сглаживает шум и выделяет тренд.",
                "признаки",
            )

    # 4) Добор производными статистики, если порог ещё не достигнут
    extra_stat = [
        ("Доверительный интервал прогноза", "Диапазон, накрывающий истинное значение с заданной вероятностью.", "статистика"),
        ("Точечный прогноз", "Одно ожидаемое значение ряда на будущий момент.", "статистика"),
        ("Остатки модели", "Разность факта и прогноза; должны быть белым шумом.", "статистика"),
        ("Сезонныйdummy-признак", "Бинарный признак месяца/дня недели для регрессий.", "признаки"),
        ("Волна жары", "Аномально тёплый период; важный кейс проверки Critic.", "климатология"),
        ("Заморозок", "Температура воздуха ниже 0 °C в тёплый сезон.", "климатология"),
        ("Индекс экстремальности", "Доля точек за пределами перцентилей P5/P95.", "климатология"),
    ]
    for term, definition, category in extra_stat:
        add(term, definition, category)

    return glossary


def main() -> None:
    parser = argparse.ArgumentParser(description="Генерация справочника терминов")
    parser.add_argument("--min-terms", type=int, default=500)
    parser.add_argument("--out", type=Path, default=OUT_PATH)
    args = parser.parse_args()

    glossary = build_glossary(min_terms=args.min_terms)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    with args.out.open("w", encoding="utf-8") as handle:
        for entry in glossary:
            handle.write(json.dumps(entry, ensure_ascii=False) + "\n")

    categories: dict[str, int] = {}
    for entry in glossary:
        categories[entry["category"]] = categories.get(entry["category"], 0) + 1
    logger.info("Справочник: %d терминов -> %s", len(glossary), args.out)
    logger.info("По категориям: %s", categories)


if __name__ == "__main__":
    sys.exit(main())
